/* zcode-workflow
description: "Динамический workflow для репозитория medai: собирает дорожную
  карту развития — обзор репозитория, четыре независимых аналитика (продукт,
  технологии, безопасность медданных, рынок), сведение предложений в три
  горизонта, независимый разбор по коду, запись ROADMAP.md в корень."
whenToUse: Когда нужно спланировать дальнейшее развитие medai и получить
  актуальный ROADMAP.md по текущему состоянию кода. Запускается из корня
  репозитория medai командой /workflow с этим воркфлоу.
*/
interface StateSummary {
  /** Что уже реализовано и работает, 8–12 строк. */
  existing: string;
  /** Слабые места, техдолги и дыры — короткие пункты. */
  weaknesses: string[];
  /** Workspace-относительные пути файлов, которые раскрывают замысел и состояние кода. */
  keyFiles: string[];
}

interface Proposal {
  /** Короткое название предложения. */
  title: string;
  /** Область: Продукт, Технологии, Безопасность или Рынок. */
  area: "Продукт" | "Технологии" | "Безопасность" | "Рынок";
  /** Зачем: какую проблему пациента, врача или клиники это решает, 1–2 предложения. */
  rationale: string;
  /** Что именно сделать: 2–4 предложения, со ссылкой на конкретные файлы, если уместно. */
  details: string;
  /** Трудоёмкость: small (пара дней), medium (до двух недель), large (больше). */
  effort: "small" | "medium" | "large";
  /** Насколько важно делать это в первую очередь: low, medium или high. */
  impact: "low" | "medium" | "high";
}

interface Critique {
  /** Что карта упустила: темы, ограничения, дешёвые быстрые победы. */
  missing: string[];
  /** Где приоритеты расставлены неверно и почему. */
  misjudged: string[];
  /** Что противоречит коду или фактам репозитория. */
  errors: string[];
  /** Вопрос, без ответа на который карта не отвечает на запрос «спланируй развитие». */
  openQuestion: string;
}

interface RoadmapResult {
  /** Workspace-относительный путь к записанному файлу карты. */
  path: string;
  /** Суть карты одним абзацем: этапы и логика приоритетов. */
  summary: string;
  /** Ровно три главных приоритета: что и почему раньше всего. */
  topPriorities: { title: string; why: string }[];
}

interface Finding {
  where: string;
  what: string;
  evidence: string;
  status: "verified" | "unconfirmed";
  severity: "low" | "medium" | "high";
}

interface WorkflowReport {
  conclusion: string;
  findings: Finding[];
  verified: string[];
  notCovered: string[];
}

artifact.board("ideas", {
  title: "Пул предложений по развитию",
  key: "title",
  status: "area",
  columns: ["Продукт", "Технологии", "Безопасность", "Рынок"],
  cardTitle: "title",
  detail: [
    { field: "impact", label: "Важность" },
    { field: "effort", label: "Трудоёмкость" },
  ],
});

phase("Изучить текущее состояние проекта");
const state = await agent("Обзорщик проекта").ask<StateSummary>(
  "Составь компактную карту текущего состояния репозитория medai — медицинского сервиса " +
  "«Спектр-Диагностика» (FastAPI + SQLite на бэкенде, React + TypeScript + Vite на фронтенде). " +
  "Прочитай README.md и TECH_DEBT_AUDIT.md целиком, посмотри git log --oneline -30, " +
  "обойди backend/app (routers, services, tests) и frontend/src (pages, components). " +
  "Файлы не редактируй — только читай. Отвечай по-русски. Верни: " +
  "existing — что уже реализовано и работает, 8–12 строк; " +
  "weaknesses — слабые места, техдолги и дыры короткими пунктами; " +
  "keyFiles — 10–15 путей файлов, которые лучше всего раскрывают замысел и состояние кода.",
);
log("Обход готов: " + state.keyFiles.length + " ключевых файлов, " + state.weaknesses.length + " слабых мест");

phase("Собрать предложения с четырёх сторон");
log("Четыре независимых аналитика смотрят на проект каждый со своей стороны");
const lenses = [
  {
    name: "Аналитик продукта",
    focus:
      "продукт глазами пациента, врача и администратора клиники: каких возможностей не хватает, " +
      "что неудобно в существующих сценариях (замеры, медкарта, опросник МЗ, приёмы, чат, кабинет врача, аналитика филиала). " +
      "Полистай frontend/src/pages и components и роутеры в backend/app/routers.",
  },
  {
    name: "Технический аналитик",
    focus:
      "архитектура, надёжность и рост: техдолги, узкие места SQLite, деплой и эксплуатация, тесты и CI, " +
      "качество кода бэкенда и фронтенда. Прочитай TECH_DEBT_AUDIT.md целиком, backend/app/database.py, config.py, " +
      "services, backend/pyproject.toml и .github/workflows.",
  },
  {
    name: "Аналитик безопасности",
    focus:
      "защита медицинских данных: аутентификация и сессии, разграничение ролей пациент/врач, загрузка документов, " +
      "логирование и приватность, готовность к требованиям 152-ФЗ и практикам обращения с медданными. " +
      "Прочитай backend/app/auth.py, database.py, schemas.py, routers/auth.py и routers/documents.py.",
  },
  {
    name: "Исследователь рынка",
    focus:
      "рынок и тренды: телемедицина и пациентские порталы в России (СберЗдоровье, DOC+, МЕДСИ, интеграции с ЕМИАС и " +
      "лабораториями), тренды медицинских ИИ-сервисов, что ждут пользователи и клиники. " +
      "Пользуйся поиском в интернете (WebSearch) и опирайся на найденное; предложения формулируй применимо к этому проекту.",
  },
];
const proposals = (
  await Promise.all(
    lenses.map(async (lens) => {
      const found = await agent(lens.name).ask<Proposal[]>(
        "Ты — " + lens.name + " медицинского сервиса medai. Твой фокус: " + lens.focus + "\n\n" +
        "Сводка о проекте от обзорщика:\n" + state.existing + "\n\n" +
        "Замеченные слабые места: " + state.weaknesses.join("; ") + "\n" +
        "Ключевые файлы: " + state.keyFiles.join(", ") + "\n\n" +
        "Открой нужные файлы сам и предложи 5–8 конкретных шагов развития в своём фокусе. " +
        "Каждое предложение заполни по схеме: title, area (Продукт / Технологии / Безопасность / Рынок), " +
        "rationale, details, effort, impact. Отвечай по-русски. Файлы не редактируй — только читай.",
      );
      for (const p of found) report(p, "ideas");
      return found;
    }),
  )
).flat();
log("Собрано предложений: " + proposals.length);

// Барьер оправдан: сведение требует всех предложений сразу — дедупликация и одна шкала приоритетов.
phase("Свести предложения в дорожную карту");
const synthesizer = agent("Составитель дорожной карты");
const draft = await synthesizer.ask<string>(
  "Составь дорожную карту развития сайта medai («Спектр-Диагностика»). " +
  "Вход: обзор состояния проекта и " + proposals.length + " предложений от четырёх аналитиков.\n\n" +
  "ОБЗОР:\n" + state.existing + "\nСлабые места: " + state.weaknesses.join("; ") + "\n\n" +
  "ПРЕДЛОЖЕНИЯ:\n" + JSON.stringify(proposals, null, 1) + "\n\n" +
  "Требования к карте:\n" +
  "- сгруппируй и дедуплицируй предложения: одна идея от разных аналитиков — один пункт карты;\n" +
  "- разбей на три горизонта: «Сейчас (1–2 месяца)», «Дальше (2–4 месяца)», «Потом (долгий горизонт)»;\n" +
  "- внутри каждого горизонта — упорядоченный список с обоснованием приоритета (важность × трудоёмкость, зависимости);\n" +
  "- отдельные разделы: «Что сознательно не делаем и почему» и «Риски».\n" +
  "Пиши по-русски, конкретно и без воды; каждый пункт опирается на предложения, а где они противоречат друг другу — выбери и объясни. " +
  "Верни карту целиком как markdown-текст.",
);

phase("Независимый разбор дорожной карты");
const critique = await agent("Независимый рецензент").ask<Critique>(
  "Ты видишь проект и черновик дорожной карты впервые. Черновик:\n\n" + draft + "\n\n" +
  "Проверь карту против самого репозитория: открой README.md, TECH_DEBT_AUDIT.md и те файлы, на которые карта ссылается, " +
  "осмотри структуру backend/app и frontend/src. Ищи провалы, а не повод одобрить:\n" +
  "missing — что упущено (темы, ограничения, дешёвые быстрые победы);\n" +
  "misjudged — где приоритеты расставлены неверно и почему;\n" +
  "errors — что противоречит коду или фактам репозитория (сверяй по файлам);\n" +
  "openQuestion — один вопрос, без ответа на который карта не отвечает на запрос «спланируй дальнейшее развитие».\n" +
  "Файлы не редактируй. Отвечай по-русски.",
);

phase("Переработать карту с учётом разбора");
const final = await synthesizer.ask<RoadmapResult>(
  "Независимый рецензент разобрал твою дорожную карту.\n" +
  "Упущено: " + JSON.stringify(critique.missing) + "\n" +
  "Неверно оценено: " + JSON.stringify(critique.misjudged) + "\n" +
  "Ошибки: " + JSON.stringify(critique.errors) + "\n" +
  "Открытый вопрос: " + critique.openQuestion + "\n\n" +
  "Переработай карту: закрой каждый пункт разбора — упущенное впиши или аргументированно отклони в «Что сознательно не делаем»; " +
  "спорные факты о состоянии кода перед тем, как вписывать, проверь сам по файлам репозитория. " +
  "Запиши финальную карту в файл ROADMAP.md в корне репозитория. " +
  "Верни: path — ровно строку \"ROADMAP.md\"; summary — суть карты одним абзацем; " +
  "topPriorities — ровно три главных приоритета {title, why}: что и почему раньше всего. По-русски.",
);

try {
  await artifact.file("roadmap", final.path, {
    title: "Дорожная карта развития",
    description: "Что развивать в medai и в каком порядке: горизонты, приоритеты и сознательные отказы.",
    primary: true,
  });
} catch {
  const fixedPath = await synthesizer.ask<string>(
    "Публикация файла дорожной карты не удалась — вероятно, файла нет, он пуст или путь неверный. " +
    "Запиши финальную дорожную карту в файл в корне репозитория ещё раз " +
    "и верни ОДНОЙ строкой только workspace-относительный путь к ней.",
  );
  await artifact.file("roadmap", fixedPath.trim(), {
    title: "Дорожная карта развития",
    description: "Что развивать в medai и в каком порядке: горизонты, приоритеты и сознательные отказы.",
    primary: true,
  });
}

const result: WorkflowReport = {
  conclusion:
    "Дорожная карта развития готова: " + final.path + ". " + final.summary + " " +
    "Основа — " + proposals.length + " предложений от четырёх независимых аналитиков " +
    "(продукт, технологии, безопасность, рынок), сведённых в горизонты и проверенных независимым разбором.",
  findings: final.topPriorities.map((p, i): Finding => ({
    where: final.path,
    what: p.title + " — " + p.why,
    evidence: "приоритет подтверждён независимым разбором по файлам репозитория",
    status: "verified",
    severity: i === 0 ? "high" : "medium",
  })),
  verified: [
    "текущее состояние проекта собрано обходом репозитория: README, TECH_DEBT_AUDIT.md, git-история, структура backend и frontend",
    proposals.length + " предложений получены с четырёх независимых позиций: продукт, технологии и безопасность — по коду, рынок — по веб-поиску",
    "черновик карты прошёл независимый разбор свежим контекстом со сверкой по файлам; замечания учтены в финальной версии",
  ],
  notCovered: [
    "карта опирается на чтение кода, а не на интервью с пациентами и врачами клиники",
    "рыночная картина собрана веб-поиском; первоисточники и конкурентные данные не верифицировались глубже",
    "код не менялся и тесты не запускались — задача была планированием, не разработкой",
  ],
};
return result;